package main

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io/fs"
	"path"
	"strings"
)

// buildServiceWorker returns sw.js for site. The cache name is a hash of every
// file, so any deploy that changes content changes sw.js and clients update.
func buildServiceWorker(site fs.FS) ([]byte, error) {
	sum := sha256.New()
	files := []string{}

	err := fs.WalkDir(site, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || p == "sw.js" {
			return err
		}
		data, err := fs.ReadFile(site, p)
		if err != nil {
			return err
		}
		fmt.Fprintf(sum, "%s\x00%d\x00", p, len(data))
		sum.Write(data)

		url := "./" + p
		if path.Base(p) == "index.html" {
			// The file server redirects /x/index.html to /x/, so cache the directory URL.
			url = strings.TrimSuffix(url, "index.html")
		}
		files = append(files, url)
		return nil
	})
	if err != nil {
		return nil, err
	}

	list, err := json.Marshal(files)
	if err != nil {
		return nil, err
	}
	version := hex.EncodeToString(sum.Sum(nil))[:12]
	return []byte(strings.NewReplacer("{{VERSION}}", version, "{{FILES}}", string(list)).Replace(swTemplate)), nil
}

const swTemplate = `// Generated by the LumenDrop server at startup. Do not edit.
const CACHE = "lumen-{{VERSION}}";
const FILES = {{FILES}};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE)
      // "reload" skips the HTTP cache, so a new version never precaches an old file.
      .then((cache) => cache.addAll(FILES.map((url) => new Request(url, { cache: "reload" }))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`
